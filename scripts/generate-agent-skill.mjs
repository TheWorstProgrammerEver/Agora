import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { generateApiReference } from './agent-skill/contract-reference.mjs'
import { createStoredZip } from './agent-skill/zip.mjs'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const skillRoot = resolve(repositoryRoot, 'agent-skill/agora')
const generatedReferencePath = resolve(skillRoot, 'references/api-v1.md')
const generatedModulePath = resolve(repositoryRoot, 'supabase/functions/skill/artifact.generated.ts')

const sourcePaths = [
  'agora/SKILL.md',
  'agora/references/api-v1.md',
  'agora/references/examples.md',
  'agora/references/operator-guide.md'
]

const forbiddenPublicContent = [
  ['agent application key', /agora_agent_v1_[A-Za-z0-9_-]{43}/],
  ['JWT', /eyJ[A-Za-z0-9_-]{12,}\.[A-Za-z0-9_-]{12,}\.[A-Za-z0-9_-]{12,}/],
  ['private key', /-----BEGIN (?:EC |OPENSSH |RSA )?PRIVATE KEY-----/],
  ['secret project key', /sb_secret_[A-Za-z0-9_-]+/],
  ['private home path', /\/home\/(?!my-user(?:\/|$))[^/\s]+/],
  ['private network address', /(?:192\.168|10\.\d{1,3})\.\d{1,3}\.\d{1,3}/]
]

export const assertSafeSkillSources = (sources) => {
  const content = sources.map(({ source }) => source).join('\n')
  for (const [label, pattern] of forbiddenPublicContent) {
    if (pattern.test(content)) throw new Error(`Agora skill source contains forbidden ${label} content.`)
  }
}

const generatedModule = ({ archive, digest, version }) => `// Generated by scripts/generate-agent-skill.mjs. Do not edit.\n\nexport const skillArtifactBase64 = '${archive.toString('base64')}'\nexport const skillArtifactEtag = '"sha256-${digest}"'\nexport const skillArtifactFilename = 'agora-codex-skill-v${version}.zip'\nexport const skillArtifactVersion = '${version}'\n`

export const buildAgentSkill = async () => {
  const apiReference = generateApiReference({
    contractPath: resolve(repositoryRoot, 'common/agoraRequestContract.ts'),
    dtoPath: resolve(repositoryRoot, 'common/agoraDtos.ts'),
    identifiersPath: resolve(repositoryRoot, 'common/agoraRequestIdentifiers.ts')
  })
  const versionMatch = apiReference.match(/Contract version: `([^`]+)`/)
  if (!versionMatch) throw new Error('Generated Agora API reference has no contract version.')

  const sources = await Promise.all(sourcePaths.map(async (name) => ({
    name,
    source: name.endsWith('/api-v1.md')
      ? apiReference
      : await readFile(resolve(skillRoot, name.replace(/^agora\//, '')), 'utf8')
  })))
  assertSafeSkillSources(sources)
  const archive = createStoredZip(sources)
  const digest = createHash('sha256').update(archive).digest('hex')

  return {
    apiReference,
    archive,
    generatedModule: generatedModule({ archive, digest, version: versionMatch[1] }),
    sourcePaths,
    version: versionMatch[1]
  }
}

const check = async () => {
  const built = await buildAgentSkill()
  const [reference, module] = await Promise.all([
    readFile(generatedReferencePath, 'utf8'),
    readFile(generatedModulePath, 'utf8')
  ])
  if (reference !== built.apiReference || module !== built.generatedModule) {
    throw new Error('Generated Agora skill artifacts have drifted; run npm run generate:agent-skill.')
  }
}

const write = async () => {
  const built = await buildAgentSkill()
  await Promise.all([
    writeFile(generatedReferencePath, built.apiReference),
    writeFile(generatedModulePath, built.generatedModule)
  ])
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const command = process.argv[2]
  if (command === '--check') await check()
  else if (command === undefined) await write()
  else throw new Error('Usage: node scripts/generate-agent-skill.mjs [--check]')
}
